// Arithmetic Operators

 let a=5;
 let b=2;


 console.log("a=5 , b =2");
 console.log("a + b =", a + b );
 console.log("a - b =", a - b);
 console.log("a * b =", a * b);
 console.log("a / b =", a / b);
 console.log("a % b =", a % b);
 console.log("a ** b =", a ** b);

// Unary  Operators 

let c=5;
let d=2;

console.log("c++ =", c++);
console.log("d-- =", d--);
console.log("c++ =", ++c);
console.log("d-- =", --d);

